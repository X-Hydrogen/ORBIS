                s1 = ELEMENT_SYM.get(n1, '?')
                s2 = ELEMENT_SYM.get(n2, '?')
                dist_3d = float(np.linalg.norm(p2 - p1))
                r1 = COVALENT_R.get(s1, 1.5)
                r2 = COVALENT_R.get(s2, 1.5)
                cov_cut = (r1 + r2) * 1.3

                is_hbond = False
                hb_cut = 2.5
                if s1 == 'H' and s2 in ('N', 'O', 'F', 'Cl'):
                    is_hbond = dist_3d > cov_cut and dist_3d < hb_cut
                elif s2 == 'H' and s1 in ('N', 'O', 'F', 'Cl'):
                    is_hbond = dist_3d > cov_cut and dist_3d < hb_cut

                draw = dist_3d < cov_cut or is_hbond
                if not draw:
                    continue

                _, _, u1, v1, d1 = atom_proj[ia]
                _, _, u2, v2, d2 = atom_proj[ib]
                avg_d = (d1 + d2) / 2.0
                if avg_d > max_vis_dist:
                    continue
                alpha = max(0.2, 1.0 - avg_d * 0.4)
                ls = '--' if is_hbond else '-'
                lw = 1.0 if is_hbond else 1.8
                ax.plot([u1, u2], [v1, v2], color='#333333',
                        linestyle=ls, linewidth=lw, alpha=alpha, zorder=8)

