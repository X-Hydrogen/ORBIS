    if not pt_s:
        raise SystemExit("ERROR: --plane-point is required with --plane-normal.")
    n = np.array([float(v) for v in norm_s.split(",")])
    nl = np.linalg.norm(n)
    if nl < 1e-12:
        raise SystemExit("ERROR: Normal vector must be non-zero.")
    n /= nl
    pt = np.array([float(v) for v in pt_s.split(",")])
    return n, pt

